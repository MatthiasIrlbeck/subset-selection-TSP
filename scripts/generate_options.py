#!/usr/bin/env python3
"""Generate all configuration surfaces from config/options.json.

The committed outputs deliberately remain buildable without Python.  CI runs
this script with --check so a change to defaults, CLI parsing, validation, help,
JSON configuration, or the result-schema config object cannot drift from the
single metadata source.
"""
