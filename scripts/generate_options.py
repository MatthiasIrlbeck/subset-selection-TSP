HEADER = "// Generated by scripts/generate_options.py from config/options.json. DO NOT EDIT.\n"


def fail(message: str) -> "NoReturn":
    raise SystemExit(f"option metadata error: {message}")


def load_metadata() -> dict[str, Any]:
    data = json.loads(METADATA_PATH.read_text(encoding="utf-8"))
    if data.get("metadata_version") != 1:
        fail("unsupported metadata_version")
    options = data.get("options")
    if not isinstance(options, list) or not options:
        fail("options must be a nonempty list")
    seen_ids: set[str] = set()
    seen_cli: set[str] = set()
    seen_fields: set[tuple[str, str]] = set()
    seen_json: set[str] = set()
    sections = {entry["id"] for entry in data.get("sections", [])}
    for option in options:
        option_id = option.get("id")
        if not isinstance(option_id, str) or not option_id:
            fail("every option needs a nonempty id")
        if option_id in seen_ids:
            fail(f"duplicate id {option_id}")
        seen_ids.add(option_id)
        if option.get("section") not in sections:
            fail(f"{option_id}: unknown section {option.get('section')}")
        cli = option.get("cli")
        for flag in ([cli] if cli else []) + list(option.get("aliases", [])):
            if not isinstance(flag, str) or not flag.startswith("--"):
                fail(f"{option_id}: invalid CLI flag {flag!r}")
            if flag in seen_cli:
                fail(f"duplicate CLI flag {flag}")
            seen_cli.add(flag)
        if option.get("declare", True):
            struct = option.get("struct")
            member = option.get("member")
            cpp_type = option.get("cpp_type")
            if struct not in {"run", "solver", "oracle"} or not member or not cpp_type:
                fail(f"{option_id}: declared fields need struct/member/cpp_type")
            field = (struct, member)
            if field in seen_fields:
                fail(f"duplicate field {struct}.{member}")
            seen_fields.add(field)
        if option.get("emit_json", True) and option.get("json_key"):
            key = option["json_key"]
            if key in seen_json:
                fail(f"duplicate emitted JSON key {key}")
            seen_json.add(key)
    return data


def cpp_default(option: dict[str, Any]) -> str:
    if "cpp_default" in option:
        return str(option["cpp_default"])
    value = option.get("default")
    cpp_type = option["cpp_type"]
    if cpp_type == "bool":
        return "true" if value else "false"
    if cpp_type == "std::string":
        return json.dumps(str(value))
    if cpp_type == "double":
        if isinstance(value, int):
            return f"{value}.0"
        return repr(float(value))
    if cpp_type == "std::vector<double>":
        return "{}" if not value else "{" + ", ".join(repr(float(x)) for x in value) + "}"
    if cpp_type == "std::optional<int>":
        return "std::nullopt" if value is None else str(int(value))
    return str(value)


def cpp_value(option: dict[str, Any], value: Any) -> str:
    temporary = dict(option)
    temporary.pop("cpp_default", None)
    temporary["default"] = value
    return cpp_default(temporary)


def access(option: dict[str, Any]) -> str:
    struct = option["struct"]
    member = option["member"]
    if struct == "run":
        return f"opt.{member}"
    if struct == "solver":
        return f"opt.solver.{member}"
    if struct == "oracle":
        return f"opt.solver.oracle.cfg.{member}"
    fail(f"{option['id']}: unknown struct")


def default_text(option: dict[str, Any]) -> str | None:
    if option.get("show_default", True) is False:
        return None
    if option.get("action") in {"help", "self_test", "quick", "p_values", "p_range", "p_file"}:
        return None
    if option.get("id") in {"point_seed", "search_seed"}:
        return "--seed"
    value = option.get("default")
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return None
    if isinstance(value, list):
        return ",".join(str(x) for x in value)
    return str(value)


def render_fields(data: dict[str, Any], struct: str) -> str:
    lines = [HEADER.rstrip(), ""]
    for option in data["options"]:
        if not option.get("declare", True) or option.get("struct") != struct:
            continue
        description = str(option.get("help", option["id"]))
        for line in textwrap.wrap(description, width=86):
            lines.append(f"    // {line}")
        lines.append(
            f"    {option['cpp_type']} {option['member']} = {cpp_default(option)};"
        )
    lines.append("")
    return "\n".join(lines)


